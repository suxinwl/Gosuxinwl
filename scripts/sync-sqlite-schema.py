"""Generate SQLite seeds from this repository's MySQL seed (not arbitrary SQL).

Run after editing gosuxin.sql; review and commit both dialects together.
SQLite explicit empty defaults preserve the seed's MySQL non-strict insert behavior.
"""
from pathlib import Path
import re
import sqlite3

ROOT = Path(__file__).resolve().parents[1]


def convert(source: str) -> str:
    source = re.sub(r"/\*.*?\*/", "", source, flags=re.S)
    source = re.sub(r"^SET .*?;\s*$", "", source, flags=re.M)
    indexes = []

    def table(match):
        name, body = match.group(1), match.group(2)
        auto = bool(re.search(r"AUTO_INCREMENT", body))
        lines = []
        for original in body.splitlines():
            line = original.strip().rstrip(",")
            if not line:
                continue
            index = re.match(r"INDEX `([^`]+)`\((.*?)\) USING BTREE", line)
            if index:
                indexes.append(f"CREATE INDEX `{name}_{index[1]}` ON `{name}` ({index[2]});")
                continue
            if auto and line.startswith("PRIMARY KEY"):
                continue
            line = re.sub(r" COMMENT '(?:[^']|'')*'", "", line)
            line = re.sub(r"enum\([^)]*\)", "TEXT", line, flags=re.I)
            line = re.sub(r" CHARACTER SET \w+ COLLATE \w+", " COLLATE NOCASE", line)
            line = line.replace(" USING BTREE", "").replace(" UNSIGNED", "")
            line = line.replace(" ON UPDATE CURRENT_TIMESTAMP", "")
            if "AUTO_INCREMENT" in line:
                line = re.sub(r"int\(\d+\) NOT NULL AUTO_INCREMENT", "INTEGER PRIMARY KEY AUTOINCREMENT", line)
            elif line.startswith("`") and "NOT NULL" in line and "DEFAULT" not in line:
                default = "''" if re.search(r"\b(?:varchar|char|text|longtext|mediumtext)\b", line, re.I) else "0"
                line += " DEFAULT " + default
            lines.append("  " + line)
        return f"CREATE TABLE IF NOT EXISTS `{name}` (\n" + ",\n".join(lines) + "\n);"

    source = re.sub(r"CREATE TABLE(?: IF NOT EXISTS)? `([^`]+)`\s*\((.*?)\) ENGINE[^;]*;", table, source, flags=re.S)
    source = source.replace("NOW()", "CURRENT_TIMESTAMP")
    source = source.replace("ON DUPLICATE KEY UPDATE `meta_value` = VALUES(`meta_value`)",
                            "ON CONFLICT (`meta_key`) DO UPDATE SET `meta_value` = excluded.`meta_value`, `updated_at` = CURRENT_TIMESTAMP")
    def literal(match):
        value = match[0][1:-1].replace("''", "'")
        escapes = {"n": "\n", "r": "\r", "t": "\t", "b": "\b", "Z": "\x1a"}
        value = re.sub(r"\\(.)", lambda m: escapes.get(m[1], m[1]), value)
        return "'" + value.replace("'", "''") + "'"
    source = re.sub(r"'(?:[^'\\]|\\.|'')*'", literal, source)
    return ("-- SQLite dialect. Generated by scripts/sync-sqlite-schema.py.\n" + source.strip() + "\n" + "\n".join(indexes)).rstrip() + "\n"


if __name__ == "__main__":
    for source, target in [
        ("devsource/developer/install/gosuxin.sql", "devsource/developer/install/sqlite.sql"),
        ("manifest/sql/v1.0.0.sql", "manifest/sql/v1.0.0.sqlite.sql"),
    ]:
        result = convert((ROOT / source).read_text(encoding="utf-8"))
        # Reject invalid generated SQL before replacing the checked-in seed.
        with sqlite3.connect(":memory:") as db:
            db.executescript(result)
        (ROOT / target).write_text(result, encoding="utf-8", newline="\n")
        print(target)
